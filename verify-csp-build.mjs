import fs from 'node:fs';
import crypto from 'node:crypto';
const h=fs.readFileSync('dist/index.html','utf8');
const headers=fs.readFileSync('dist/_headers','utf8');
const manifest=JSON.parse(fs.readFileSync('dist/csp-manifest.json','utf8'));
const fail=[];const need=(c,m)=>{if(!c)fail.push(m);};
const hash=s=>`'sha256-${crypto.createHash('sha256').update(s,'utf8').digest('base64')}'`;
const scripts=[...h.matchAll(/<script\s+([^>]*)>([\s\S]*?)<\/script>/gi)].filter(m=>/data-tr-(?:build|style-attr-runtime|reports-purity-runtime|structural-runtime|state-runtime|persistence-coalescing-runtime|security-runtime|event-runtime|csp-runtime|style-runtime|operation-cleanup-runtime|render-closure-runtime)=/.test(m[1]));
const styles=[...h.matchAll(/<style\s+([^>]*)>([\s\S]*?)<\/style>/gi)].filter(m=>/data-tr-build=/.test(m[1]));
need(scripts.length===12,`Esperaba 12 scripts propios, hay ${scripts.length}.`);
need(styles.length===1,`Esperaba 1 style propio, hay ${styles.length}.`);
const sh=scripts.map(m=>hash(m[2])),sth=styles.map(m=>hash(m[2]));
for(const x of sh)need(headers.includes(x),`Hash de script no publicado en _headers: ${x}`);
for(const x of sth)need(headers.includes(x),`Hash de style no publicado en _headers: ${x}`);
need(JSON.stringify(sh)===JSON.stringify(manifest.scriptHashes),'csp-manifest scriptHashes no coincide con dist/index.html.');
need(sth[0]===manifest.styleHash,'csp-manifest styleHash no coincide con dist/index.html.');
need(/Content-Security-Policy:\s+default-src 'none';/.test(headers),'Falta CSP enforced en _headers.');
need(/script-src-attr 'none'/.test(headers),'script-src-attr no está bloqueado.');
need(!/script-src[^\n;]*'unsafe-inline'/.test(headers),'unsafe-inline aparece en política de scripts.');
need(!/'unsafe-eval'/.test(headers),'unsafe-eval aparece en _headers.');
need(/style-src-attr 'none'/.test(headers),'style-src-attr no está bloqueado.');
need(!/style-src-attr[^\n;]*'unsafe-inline'/.test(headers),'unsafe-inline permanece en style-src-attr.');
need(/frame-ancestors 'none'/.test(headers),'frame-ancestors no está bloqueado.');
const cspLine=headers.split(/\r?\n/).find(x=>x.includes('Content-Security-Policy:'))||'';
need(cspLine.length<2000,`La línea CSP supera el límite de Cloudflare (${cspLine.length}).`);
if(fail.length){console.error('CSP build verification FAILED');for(const f of fail)console.error(' - '+f);process.exit(1);}
console.log('CSP build verification OK');
console.log(` - Script hashes verified: ${sh.length}/${sh.length}`);
console.log(` - Style hashes verified: ${sth.length}/${sth.length}`);
console.log(` - _headers CSP line: ${cspLine.length} chars (< 2000)`);
console.log(' - Scripts: no unsafe-inline / no unsafe-eval');
console.log(" - Style attributes: style-src-attr 'none'");
